"""Renders eval/results.md from raw result files (spec §9.1 rule 4, §9.11).

results.md is only ever written by this script, from files under eval/results/, so no
number in it can be typed by hand. Sections without results yet say "⏳ not run".
Phase 2 fills the retrieval benchmark; the agent sections are filled from Phase 6 on.

Usage: python eval/report.py
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "eval" / "results"
NOT_RUN = "⏳ not run"


def _retrieval_section(bench: dict | None) -> list[str]:
    lines = ["## Retrieval benchmark (no LLM)", ""]
    if bench is None:
        return [*lines, NOT_RUN, ""]
    meta = bench["meta"]
    lines += [
        f"Embedding model `{meta.get('embedding_model', '?')}` · data seed {meta.get('data_seed', '?')} · "
        f"git `{meta.get('git_sha', '?')}` · run {meta.get('run_date', '?')} · "
        "queries: "
        + " · ".join(f"{n} {kind}" for kind, n in meta.get("n_queries", {}).items())
        + f". Recall and MRR use the top {meta.get('top_k', 10)} hits.",
        "",
        "| Mode | E r@1 | E r@5 | P r@1 | P r@5 | D r@1 | D r@5 | MRR | Negatives flagged weak |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    weak = f"{bench['negatives_weak_rate']:.0%}"
    for mode in ("bm25", "dense", "hybrid"):
        s = bench["modes"][mode]
        cells = [f"{s[t][k]:.2f}" for t in ("E", "P", "D") for k in ("recall@1", "recall@5")]
        lines.append(f"| {mode} | " + " | ".join(cells) + f" | {s['all']['mrr']:.2f} | {weak} |")
    lines += [
        "",
        "The match signal is the same in every mode, so the last column does not vary by mode.",
        "",
        f"### Match-quality threshold τ = {bench['chosen_tau']:.2f}",
        "",
        "Chosen as the grid value with the best macro-F1 of strong (E, P, D) versus weak (N);",
        "on a plateau of equal scores the middle value is taken.",
        "",
        "| τ | macro-F1 | E/P/D flagged strong | N flagged weak |",
        "|---|---|---|---|",
    ]
    for row in bench["tau_sweep"]:
        lines.append(
            f"| {row['tau']:.2f} | {row['macro_f1']:.3f} | "
            f"{row['strong_rate_positive']:.0%} | {row['weak_rate_negative']:.0%} |"
        )
    return [*lines, ""]


def render_results(bench: dict | None) -> str:
    lines = [
        "# Evaluation Results",
        "",
        "Run metadata: model `—` · prompt `—` · data seed 42 · agent runs: none yet.",
        "All data is synthetic. This page is generated by `eval/report.py`; do not edit it by hand.",
        "",
        *_retrieval_section(bench),
    ]
    for title in (
        "Agent — full system (3 repeats, mean ± std, 95% CI)",
        "Abstention",
        "Ablation (leave-one-out)",
        "Operational",
        "Error analysis",
        "Threats to validity",
    ):
        lines += [f"## {title}", "", NOT_RUN, ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render eval/results.md from raw results.")
    parser.add_argument("--out", type=Path, default=ROOT / "eval" / "results.md")
    args = parser.parse_args(argv)
    bench_path = RESULTS / "retrieval_bench_v1.json"
    bench = json.loads(bench_path.read_text(encoding="utf-8")) if bench_path.is_file() else None
    args.out.write_bytes(render_results(bench).encode("utf-8"))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
